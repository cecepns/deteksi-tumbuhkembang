        "Beberapa kemampuan komunikasi belum tercapai sesuai usia. Tingkatkan stimulasi dengan berbicara lebih sering kepada anak, ajak menunjuk benda sambil menyebutkan namanya, bacakan buku cerita, dan kurangi waktu layar. Gunakan panduan ide stimulasi sesuai kelompok usia anak.",
